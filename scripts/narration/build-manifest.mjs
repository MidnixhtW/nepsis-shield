// Writes src/content/narrationManifest.ts: which recorded clips exist for each reader, from the files in public/audio.
//   node scripts/narration/build-manifest.mjs
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "../..");
const AUDIO = path.join(ROOT, "public", "audio");
const OUT = path.join(ROOT, "src", "content", "narrationManifest.ts");

const voices = existsSync(AUDIO) ? readdirSync(AUDIO, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort() : [];
const manifest = Object.fromEntries(
  voices.map((voice) => [voice, readdirSync(path.join(AUDIO, voice)).filter((f) => /^[0-9a-f]{16}\.mp3$/.test(f)).map((f) => f.slice(0, 16)).sort()]),
);

const body = Object.entries(manifest)
  .map(([voice, ids]) => `  ${voice}: [\n${ids.map((id) => `    "${id}",`).join("\n")}\n  ],`)
  .join("\n");

writeFileSync(
  OUT,
  `// Generated by scripts/narration/build-manifest.mjs from public/audio. Do not edit by hand.\n` +
    `// Each id is clipId(spokenText(...)) from src/lib/narrationText.ts; the file is public/audio/<reader>/<id>.mp3.\n` +
    `export const NARRATION_CLIPS: Record<string, readonly string[]> = {\n${body}\n};\n`,
);
console.log(Object.entries(manifest).map(([v, ids]) => `${v}: ${ids.length}`).join(", "));
